-- 8. Notifications Table
CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id TEXT NOT NULL,
  message TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'info',
  is_read BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS for Notifications
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;

-- Select Policy: Users can only see their own notifications, unless HR/Partner
CREATE POLICY select_notifications ON notifications
  FOR SELECT
  TO authenticated
  USING (
    employee_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM profiles
      WHERE profiles.id = auth.uid()
      AND profiles.role IN ('HR', 'Partner')
    )
  );

-- Insert Policy: Users can insert notifications
CREATE POLICY insert_notifications ON notifications
  FOR INSERT
  TO authenticated
  WITH CHECK (TRUE);

-- 9. Supabase Storage Buckets & Policies for DPDP Act compliance
-- Create the attendance-selfies bucket
INSERT INTO storage.buckets (id, name, public)
VALUES ('attendance-selfies', 'attendance-selfies', false)
ON CONFLICT (id) DO NOTHING;

-- RLS policies for storage objects in attendance-selfies bucket
-- Allow authenticated employees to upload selfies (insert objects)
CREATE POLICY "Allow employees to upload selfies" ON storage.objects
  FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'attendance-selfies'
    AND (storage.foldername(name))[1] = auth.uid()
  );

-- Allow only HR and Partner to read/download selfies (select objects)
CREATE POLICY "Allow HR and Partners to view selfies" ON storage.objects
  FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'attendance-selfies'
    AND EXISTS (
      SELECT 1 FROM public.profiles
      WHERE public.profiles.id = auth.uid()
      AND public.profiles.role IN ('HR', 'Partner')
    )
  );

-- Allow employees to read/view their own selfies
CREATE POLICY "Allow employees to view own selfies" ON storage.objects
  FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'attendance-selfies'
    AND (storage.foldername(name))[1] = auth.uid()
  );
